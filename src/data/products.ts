// ─── Helper Functions ─────────────────────────────────────────────────────────

export const getProductBySlug = (slug: string): Product | undefined =>
  products.find((p) => p.slug === slug);

export const getProductById = (id: string): Product | undefined =>
  products.find((p) => p.id === id);

export const getProductsByCategory = (category: string): Product[] =>
  products.filter((p) => p.category.toLowerCase() === category.toLowerCase());

export const getProductsBySubcategory = (subcategory: string): Product[] =>
  products.filter((p) => p.subcategory?.toLowerCase() === subcategory.toLowerCase());

export const getNewArrivals = (): Product[] =>
  products.filter((p) => p.status === 'new').slice(0, 8);

export const getBestSellers = (): Product[] =>
  products.filter((p) => p.status === 'best-seller').slice(0, 8);

export const getTrendingProducts = (): Product[] =>
  products.filter((p) => p.status === 'trending').slice(0, 8);

export const getSaleProducts = (): Product[] =>
  products.filter((p) => p.discount && p.discount > 0).slice(0, 12);

export const getRelatedProducts = (productId: string, category: string, limit = 4): Product[] =>
  products
    .filter((p) => p.id !== productId && p.category === category)
    .slice(0, limit);

export const searchProducts = (query: string): Product[] => {
  const q = query.toLowerCase();
  return products.filter(
    (p) =>
      p.name.toLowerCase().includes(q) ||
      p.brand.toLowerCase().includes(q) ||
      p.category.toLowerCase().includes(q) ||
      p.tags.some((t) => t.toLowerCase().includes(q))
  );
};

export const getFeaturedProducts = (): Product[] =>
  products.filter((p) => p.status === 'best-seller' || p.status === 'new').slice(0, 6);

export const getAllBrands = (): string[] =>
  [...new Set(products.map((p) => p.brand))].sort();

export const getAllColors = (): string[] =>
  [...new Set(products.flatMap((p) => p.colors?.map((c) => c.name) ?? []))].sort();

export const getAllSizes = (): string[] =>
  [...new Set(products.flatMap((p) => p.sizes?.map((s) => s.label) ?? []))].sort();
